"""Export the exact Python packages inside PerfCrew's vLLM serving image (the one bench/modal_bench.py runs).

    modal run bench/freeze_stack.py      -> serving/vllm-stack.txt

CPU only: no GPU is started. Snyk scans this file to cover the real serving stack, not just our own pins.
"""
from pathlib import Path

import modal

VLLM_VERSION = "0.32.0"  # keep in sync with bench/modal_bench.py
app = modal.App("perfcrew-freeze")
# Same package layer as the benchmark image (cached by Modal), without the local source files.
image = modal.Image.debian_slim(python_version="3.12").pip_install(f"vllm=={VLLM_VERSION}")
OUT = Path(__file__).resolve().parent.parent / "serving" / "vllm-stack.txt"


@app.function(image=image, timeout=600)
def freeze() -> str:
    import subprocess
    return subprocess.run(["pip", "freeze", "--all"], capture_output=True, text=True, check=True).stdout


@app.local_entrypoint()
def main():
    pins = sorted(l for l in freeze.remote().splitlines() if "==" in l and not l.startswith("-e"))
    OUT.write_text(f"# Exact packages in PerfCrew's serving image: vllm=={VLLM_VERSION} on Modal (Linux, CUDA).\n"
                   f"# Generated by `modal run bench/freeze_stack.py`. Scanned by `perfcrew scan --stack vllm`.\n"
                   + "\n".join(pins) + "\n")
    print(f"{len(pins)} packages -> {OUT}")
